def _import_and_typecheck(output: Path) -> object:
    spec = importlib.util.spec_from_file_location(output.stem, output)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    result = subprocess.run(
        [sys.executable, "-m", "mypy", "--strict", str(output)],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    return module


def test_keywords_and_colliding_ids_generate_valid_modules(tmp_path: Path) -> None:
    definition = parse_definition(
        """
[requires]
"a.import" = "string"
"items[0].class" = "number"
"items[0].def" = "number"
"x.y.z" = "boolean"
"x_y.z" = "boolean"

[questions.class]
type = "noul"

[questions."a.b"]
type = "noul"

[questions.a_b]
type = "choice"
criteria = { yes = "Yes", no = "No" }

[questions."a-b"]
type = "score"
criteria = ["Low", "High"]

[factors]
def = { all = ["class"] }
""",
        filename="keywords.toml",
    )
    output = generate(definition, tmp_path / "keywords_generated.py", source_name="keywords.toml")
    text = output.read_text(encoding="utf-8")
    aliases = [line for line in text.splitlines() if line.startswith("class _") and "Answer" in line]
    assert len(aliases) == 4 and len(set(aliases)) == 4, aliases
    module = _import_and_typecheck(output)
    module.assert_state(  # type: ignore[attr-defined]
        {
            "a": {"import": "x"},
            "items": [{"class": 1, "def": 2}],
            "x": {"y": {"z": True}},
            "x_y": {"z": False},
        }
    )
    factors = module.evaluate_factors(  # type: ignore[attr-defined]
        {
            "class": {"type": "noul", "noul": 0.9},
            "a.b": {"type": "noul", "noul": 0.1},
            "a_b": {"type": "choice", "choice": "yes", "confidence": 0.9, "probabilities": {}},
            "a-b": {"type": "score", "score": 1.0, "confidence": 0.9, "legend": {}, "probabilities": {}},
        }
    )
    assert factors == {"def": True}


def test_empty_tables_typecheck_under_strict_mypy(tmp_path: Path) -> None:
    definition = parse_definition('[questions.q]\ntype = "noul"\n', filename="minimal.toml")
    output = generate(definition, tmp_path / "minimal_generated.py", source_name="minimal.toml")
    text = output.read_text(encoding="utf-8")
    assert "meta: dict[str, Any] = {}" in text
    assert "requires: dict[str, str] = {}" in text
    assert "factor_definitions: dict[str, dict[str, Any]] = {}" in text
    module = _import_and_typecheck(output)
    assert module.evaluate_factors({"q": {"type": "noul", "noul": 0.2}}) == {}  # type: ignore[attr-defined]


def test_generated_module_exports_application_data(tmp_path: Path) -> None:
    definition = parse_definition(
        '''
[questions.topic]
type = "choice"
criteria = { cost = "Prices", timing = "Timing" }

[data]
labels = { cost = "Delivery prices", timing = "Delivery times" }
templates = [
  { id = "cost", text = "{method_label} costs {price_label}." },
]
''',
        filename="delivery.toml",
    )
    output = generate(definition, tmp_path / "delivery_generated.py", source_name="delivery.toml")
    module = _import_and_typecheck(output)
    assert module.data == {
        "labels": {"cost": "Delivery prices", "timing": "Delivery times"},
        "templates": [{"id": "cost", "text": "{method_label} costs {price_label}."}],
    }


def test_indexed_requirements_emit_element_types() -> None:
    definition = parse_definition(
        '[requires]\n"tickets[0].message" = "string"\n\n[questions.urgent]\ntype = "noul"\n',
        filename="indexed.toml",
    )
    rendered = render_definition(definition, source_name="indexed.toml")
    assert "tickets: list[" in rendered
    assert "message: str" in rendered
    assert "list[Any]" not in rendered
    wildcard = parse_definition(
        '[requires]\n"tickets[].message" = "string"\n\n[questions.urgent]\ntype = "noul"\n',
        filename="wildcard.toml",
    )
    wildcard_rendered = render_definition(wildcard, source_name="wildcard.toml")
    assert "tickets: list[" in wildcard_rendered
    assert "message: str" in wildcard_rendered
    assert "list[Any]" not in wildcard_rendered
