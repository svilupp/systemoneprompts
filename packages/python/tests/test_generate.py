def test_render_embeds_source_hash_and_types() -> None:
    definition = parse_definition(fixture("golden/triage.toml"), filename="triage.toml")
    out = render_definition(definition, source_name="triage.toml")
    assert "generated by systemoneprompts — do not edit. source: triage.toml sha256:" in out
    assert "class RequiredState" in out or "RequiredState = TypedDict" in out
    assert "class Answers" in out or "Answers = TypedDict" in out
    assert "class Factors" in out or "Factors = TypedDict" in out
    assert "assert_state = create_state_assert(requires)" in out
    assert "cast(Callable[[Answers], Factors], create_factor_evaluator(factor_definitions))" in out
    assert "spam.requests_credentials" in out
    assert "message: str" in out
    assert "open_orders: list[Any]" in out
    assert "class RequiredState(TypedDict):" in out
    assert "class Answers(TypedDict):" in out or "Answers = TypedDict('Answers'" in out
    assert "returns None" in out
    assert "total=False" not in out


def test_generate_lists_every_error() -> None:
    bad = """
[questions.topic]
type = "choice"
instructions = "Which?"
criteria = { billing = "Charges", orders = "Shipments" }

[questions.frustration]
type = "score"
instructions = "How?"
criteria = ["Calm", "Angry"]

[factors]
x = { ref = "topic", choice = "nope" }
y = { all = ["frustration"] }
"""
    definition = parse_definition(bad, filename="bad.toml")
    with pytest.raises(SystemOnePromptsError) as caught:
        generate(definition, Path("unused.py"), source_name="bad.toml")
    codes = sorted(item.code for item in caught.value.diagnostics)
    assert "unknown-option" in codes
    assert "non-boolean-ref" in codes


def test_generated_module_imports_and_typechecks(tmp_path: Path) -> None:
    definition = parse_definition(fixture("golden/triage.toml"), filename="triage.toml")
    output = generate(definition, tmp_path / "triage_generated.py", source_name="triage.toml")
    spec = importlib.util.spec_from_file_location("triage_generated", output)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    module.assert_state(
        {
            "ticket": {"message": "hi", "sender": {"email": "a@b.c", "display_name": "A"}},
            "customer": {"open_orders": []},
            "policy": {"sensitive_credentials": []},
        }
    )
    result = subprocess.run(
        [sys.executable, "-m", "mypy", "--strict", str(output)],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result.stdout + result.stderr


